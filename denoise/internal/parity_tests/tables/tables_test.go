// TestTrigResolution answers the load-bearing question: does Go stdlib
// trig reproduce the twiddle bits the port relies on?
//
//	embedded-vs-baked:  the Go embedded table vs the C baked constants
//	                    (the actual shipping-parity guarantee).
//	live-libm-vs-baked: this machine's libm compute_twiddles vs the
//	                    baked constants (were the constants generated by
//	                    a bit-identical libm?).
//	go-trig-vs-live:    Go math.Cos/Sin vs this machine's libm for the
//	                    exact phases (the definitive Go-vs-libm answer).
//
// The port EMBEDS regardless (upstream ships the tables as constants);
// this test records the evidence and fails loudly only on the shipping
// guarantee (embedded-vs-baked). The two informational comparisons are
// reported via t.Log and a soft count so a divergence is visible
// without failing the gate.
func TestTrigResolution(t *testing.T) {
	const pi = 3.14159265358979323846264338327

	goTwiddle := func(i int) (r, im float32) {
		phase := (-2 * pi / float64(960)) * float64(i)
		return float32(math.Cos(phase)), float32(math.Sin(phase))
	}

	gr := rnnoise.FFTTwiddleR()
	gi := rnnoise.FFTTwiddleI()

	var liveVsBaked, goVsLive, goVsBaked int
	for i := 0; i < 960; i++ {
		br, bi := cTwiddleR(i), cTwiddleI(i)         // baked C constant
		lr, li := cLiveTwiddleR(i), cLiveTwiddleI(i) // this machine's libm
		xr, xi := goTwiddle(i)                       // Go stdlib trig

		if math.Float32bits(lr) != math.Float32bits(br) || math.Float32bits(li) != math.Float32bits(bi) {
			liveVsBaked++
		}
		if math.Float32bits(xr) != math.Float32bits(lr) || math.Float32bits(xi) != math.Float32bits(li) {
			goVsLive++
		}
		if math.Float32bits(xr) != math.Float32bits(br) || math.Float32bits(xi) != math.Float32bits(bi) {
			goVsBaked++
		}
		// Shipping guarantee: embedded table == baked C constants.
		bitsEqf(t, "embedded.r", i, br, gr[i])
		bitsEqf(t, "embedded.i", i, bi, gi[i])
	}

	t.Logf("TRIG RESOLUTION (960 twiddles):")
	t.Logf("  live-libm(this machine) vs baked-constant mismatches: %d", liveVsBaked)
	t.Logf("  Go-math.Cos/Sin        vs live-libm     mismatches: %d", goVsLive)
	t.Logf("  Go-math.Cos/Sin        vs baked-constant mismatches: %d", goVsBaked)
	if goVsBaked == 0 {
		t.Logf("  => Go stdlib trig reproduces the baked twiddles exactly; the port generates the 960-pt twiddles at init (kiss_fft.go computeTwiddles), bit-identical to the C table and with the correct signed zero at k=0.")
	} else {
		t.Logf("  => Go stdlib trig diverges from the baked twiddles on %d/960; embedding is MANDATORY (FLAC cosf-shim precedent).", goVsBaked)
	}
}
