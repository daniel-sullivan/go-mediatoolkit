// bitsEqf asserts two float32 values are identical by IEEE-754 bit
// pattern (so -0.0 vs +0.0 and NaN payloads are caught).
func bitsEqf(t *testing.T, ctx string, i int, c, g float32) {
	t.Helper()
	cb := math.Float32bits(c)
	gb := math.Float32bits(g)
	assert.Equalf(t, cb, gb, "%s[%d]: C=%v (0x%08x) Go=%v (0x%08x)", ctx, i, c, cb, g, gb)
}

// TestKFFTParams pins the static rnn_kfft scalar fields.
func TestKFFTParams(t *testing.T) {
	nfft, scale, shift, factors := rnnoise.KFFTParams()
	assert.Equal(t, cNFFT(), nfft, "nfft")
	bitsEqf(t, "scale", 0, cScale(), scale)
	assert.Equal(t, cShift(), shift, "shift")
	for i := 0; i < len(factors); i++ {
		assert.Equalf(t, cFactor(i), factors[i], "factors[%d]", i)
	}
}

